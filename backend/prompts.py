def build_system_prompt(track: str, stage_label: str, rag_hints: list = None) -> str:
    """拼装 System Prompt：赛道基础规则 + 当前阶段 + RAG 参考素材。"""
    base = TRACKS[track]["system"]
    rag_text = ""
    if rag_hints:
        rag_text = "\n\n参考素材（仅供你在提问时调用，绝不直接念给用户当答案）：\n" + "\n".join(
            f"- {h}" for h in rag_hints
        )
    return (
        f"{base}\n\n"
        f"【当前引导阶段：{stage_label}】请围绕这一阶段继续用提问推进，不要跨阶段给结论。{rag_text}"
    )
